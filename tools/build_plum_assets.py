"""Original compact Plum, thick twin-locule interiors and prepared fragments.

Run with Blender 4.3+. Geometry follows the actual authored collision profile.
Existing assets are never regenerated by this script.
"""
from pathlib import Path
import json
import math
import bpy
import bmesh
from mathutils import Matrix, Vector
from mathutils.geometry import convex_hull_2d

ROOT = Path(__file__).resolve().parents[1]
DATA = next(d for d in json.loads((ROOT/'data/tomatoes.json').read_text()) if d['id'] == 'plum')
AXES = DATA['proxy_axes']
LOBE, LOBES, TAPER = (DATA[k] for k in ['proxy_lobe', 'proxy_lobe_count', 'proxy_taper'])
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)


def material(name, color, roughness):
    m = bpy.data.materials.new(name)
    m.diffuse_color = (*color, 1)
    m.use_nodes = True
    shader = m.node_tree.nodes['Principled BSDF']
    shader.inputs['Base Color'].default_value = m.diffuse_color
    shader.inputs['Roughness'].default_value = roughness
    return m


skin = material('Plum dense brick-red skin', (.42, .040, .020), .39)
flesh = material('Plum thick terracotta flesh', (.56, .14, .075), .35)
pith = material('Plum narrow peach pith', (.79, .49, .27), .46)
gel = material('Plum twin crimson seed galleries', (.22, .030, .018), .25)
seed = material('Plum ivory teardrop seeds', (.91, .76, .46), .38)
green = material('Plum folded olive calyx', (.095, .16, .038), .66)
scar = material('Plum small blossom scar', (.19, .068, .023), .73)


def mesh(name, vertices, faces, mat, smooth=True):
    data = bpy.data.meshes.new(name)
    data.from_pydata(vertices, [], faces)
    data.update()
    ob = bpy.data.objects.new(name, data)
    bpy.context.collection.objects.link(ob)
    ob.data.materials.append(mat)
    for face in data.polygons:
        face.use_smooth = smooth
    return ob


def sphere(name, center, size, mat):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=20, ring_count=10, location=center)
    ob = bpy.context.object
    ob.name = name
    ob.scale = size
    ob.data.materials.append(mat)
    for face in ob.data.polygons:
        face.use_smooth = True
    return ob


def shape(x, y, z):
    lobe = 1+LOBE*math.cos(LOBES*math.atan2(z, x))*(1-y*y)
    taper = 1-TAPER*y
    return (x*AXES[0]*lobe*taper, y*AXES[1], z*AXES[2]*lobe*taper)


def shell(half=False):
    vertices, faces = [], []
    rings, segments = 28, 56
    for i in range(rings+1):
        a = math.pi*(.5 if half else 1)*i/rings
        for j in range(segments):
            t = math.tau*j/segments
            point = (math.cos(a), math.sin(a)*math.cos(t), math.sin(a)*math.sin(t)) if half else (math.sin(a)*math.cos(t), math.cos(a), math.sin(a)*math.sin(t))
            vertices.append(shape(*point))
    for i in range(rings):
        for j in range(segments):
            a, b = i*segments+j, i*segments+(j+1) % segments
            face = (a, b, b+segments, a+segments)
            faces.append(tuple(reversed(face)) if half else face)
    return mesh('Prepared Plum half' if half else 'Compact tapered Plum shell', vertices, faces, skin)


def crown():
    for j in range(5):
        t = math.tau*j/5
        # Two folded faces meet at a raised center vein, rather than flat leaves.
        points = [(0, AXES[1]-.012, 0),
                  (.12*math.cos(t-.50), AXES[1]+.025, .12*math.sin(t-.50)),
                  (.25*math.cos(t), AXES[1]+.095, .25*math.sin(t)),
                  (.12*math.cos(t+.50), AXES[1]+.025, .12*math.sin(t+.50)),
                  (.12*math.cos(t), AXES[1]+.077, .12*math.sin(t))]
        ob = mesh('Folded five-point Plum crown', points, [(0, 1, 4), (1, 2, 4), (2, 3, 4), (3, 0, 4)], green)
        solid = ob.modifiers.new('Thick folded calyx', 'SOLIDIFY')
        solid.thickness = .012
    for j in range(8):
        t = j/7
        sphere('Short slanted Plum stem', (.11*t, AXES[1]+.025+.16*t, -.035*t*t), (.032, .029, .031), green)
    sphere('Plum blossom scar', (0, -AXES[1]+.004, 0), (.038, .011, .035), scar)


def half():
    shell(True)
    rim = [(-.003, *shape(0, math.cos(math.tau*j/64), math.sin(math.tau*j/64))[1:]) for j in range(64)]
    mesh('Thick Plum flesh cap', [(-.003, 0, 0)]+rim, [(0, (j+1) % 64+1, j+1) for j in range(64)], flesh, False)
    sphere('Long narrow Plum central pith', (-.016, .035, 0), (.013, .40, .043), pith)
    sphere('Dense Plum shoulder pith', (-.014, .36, 0), (.014, .10, .15), pith)
    for side in [-1, 1]:
        sphere('Narrow longitudinal Plum locule', (-.014, .025, side*.19), (.012, .31, .098), gel)
        for j in range(6):
            y = -.215+j*.087
            ob = sphere('Modeled Plum gallery seed', (-.031, y, side*(.185+(.019 if j % 2 else -.019))), (.012, .034, .016), seed)
            ob.rotation_euler.x = side*(.24 if j % 2 else -.24)


def clip(normal):
    bpy.context.view_layer.update()
    n = Vector(normal).normalized()
    u = n.cross(Vector((0, 0, 1)))
    if u.length < .001:
        u = n.cross(Vector((0, 1, 0)))
    u.normalize()
    v = n.cross(u)
    for ob in list(bpy.context.scene.objects):
        ob.data.transform(ob.matrix_world)
        ob.matrix_world = Matrix.Identity(4)
        bm = bmesh.new()
        bm.from_mesh(ob.data)
        bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=.00001)
        bmesh.ops.bisect_plane(bm, geom=list(bm.verts)+list(bm.edges)+list(bm.faces),
                              plane_co=(0, 0, 0), plane_no=n, dist=.00001, clear_inner=True)
        cut = [vertex for vertex in bm.verts if abs(vertex.co.dot(n)) < .0001]
        if len(cut) >= 3:
            hull = convex_hull_2d([Vector((vertex.co.dot(u), vertex.co.dot(v))) for vertex in cut])
            if len(hull) >= 3:
                try:
                    face = bm.faces.new([cut[i] for i in hull])
                    ob.data.materials.append(flesh)
                    face.material_index = len(ob.data.materials)-1
                    face.normal_update()
                    if face.normal.dot(n) > 0:
                        face.normal_flip()
                except ValueError:
                    pass  # An existing coplanar face already closes this object.
        bm.normal_update()
        if ob.name.startswith('Prepared Plum half'):
            assert any(f.normal.dot(n) < -.99 and f.calc_area() > .01 and all(abs(vertex.co.dot(n)) < .0001 for vertex in f.verts) for f in bm.faces), 'Missing Plum flesh cap'
        bm.to_mesh(ob.data)
        bm.free()
        ob.data.update()
        if not ob.data.polygons:
            bpy.data.objects.remove(ob, do_unlink=True)


def export(relative):
    bpy.context.view_layer.update()
    for ob in list(bpy.context.scene.objects):
        bpy.context.view_layer.objects.active = ob
        for mod in list(ob.modifiers):
            bpy.ops.object.modifier_apply(modifier=mod.name)
        ob.matrix_world = Matrix.Rotation(math.pi/2, 4, 'X') @ ob.matrix_world
    count = sum(len(ob.data.vertices) for ob in bpy.context.scene.objects)
    groups = {}
    for ob in list(bpy.context.scene.objects):
        groups.setdefault(tuple(m.name for m in ob.data.materials), []).append(ob)
    for objects in groups.values():
        bpy.ops.object.select_all(action='DESELECT')
        for ob in objects:
            ob.select_set(True)
        bpy.context.view_layer.objects.active = objects[0]
        if len(objects) > 1:
            bpy.ops.object.join()
    assert sum(len(ob.data.vertices) for ob in bpy.context.scene.objects) == count, 'Batching changed Plum geometry'
    assert len(bpy.context.scene.objects) <= 8
    bpy.ops.object.select_all(action='SELECT')
    bpy.ops.export_scene.gltf(filepath=str(ROOT/relative), export_format='GLB', use_selection=True, export_apply=True)
    bpy.ops.object.delete(use_global=False)


shell()
crown()
export('assets/models/tomatoes/plum.glb')
half()
export('assets/models/fragments/plum_half.glb')
half()
clip((0, 1, 0))
export('assets/models/fragments/plum_wedge.glb')
half()
clip((0, 1, 0))
clip((1, -1, 0))
ob = sphere('Fresh diagonal Plum gallery', (.17, .17, 0), (.008, .08, .13), gel)
ob.rotation_euler.z = -math.pi/4
for z in [-.065, .065]:
    ob = sphere('Fresh diagonal Plum seed', (.162, .178, z), (.009, .025, .014), seed)
    ob.rotation_euler.z = -math.pi/4
export('assets/models/fragments/plum_chunk.glb')
for path in ['assets/models/tomatoes/plum.glb']+['assets/models/fragments/plum_'+kind+'.glb' for kind in ['half', 'wedge', 'chunk']]:
    bpy.ops.import_scene.gltf(filepath=str(ROOT/path))
bpy.ops.wm.save_as_mainfile(filepath=str(ROOT/'art/plum.blend'))
